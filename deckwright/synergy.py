"""
synergy.py — which cards hold together, and why.

DERIVATION.md judges every card vertically: against the plan, alone. This is
the missing horizontal clause -- do these cards relate to EACH OTHER?

    The graph decides which of them hold together.

An edge is directed and object-typed: A produces treasure, B consumes
artifacts, so A -> B carries {"treasure"}. The object IS the explanation, which
is why edges() returns objects and not a score -- why.py can then speak without
inventing anything.

No model. No network. Pure functions over oracle text.
"""

from __future__ import annotations

import json
import pathlib
import re
from typing import Any

REPO_DIR = pathlib.Path(__file__).resolve().parents[1]
OBJECTS_PATH = REPO_DIR / "data" / "synergy_objects.json"
FAMILIES_PATH = REPO_DIR / "data" / "mechanic_families.json"

_OBJECTS: dict[str, dict] | None = None
_SIGNALS: dict[str, dict] | None = None

# A profile we could not read. NOT an empty profile: an unknown must neither
# qualify a card for a slot nor disqualify it. The house rule, at the one place
# it is easiest to get wrong.
UNKNOWN = "unknown"
# Oracle present but no signal ∧ no keyword — Know Magic "unread". Distinct from
# UNKNOWN (could not look) and from a readable card with no edges (real none).
UNREAD = "unread"
# UI/API copy when unknown or unread would otherwise look like zero synergy.
COULD_NOT_READ = "could not read — not the same as no synergy"


def load_objects(path: pathlib.Path | None = None) -> dict[str, dict]:
    """The closed object set. Generated by scripts/derive_synergy_objects.py."""
    global _OBJECTS
    if _OBJECTS is None or path is not None:
        payload = json.loads((path or OBJECTS_PATH).read_text())
        objs = payload.get("objects") or {}
        if path is None:
            _OBJECTS = objs
        return objs
    return _OBJECTS


def load_signals(path: pathlib.Path | None = None) -> dict[str, dict]:
    """oracle_signals from mechanic_families.json, with produces/consumes."""
    global _SIGNALS
    if _SIGNALS is None or path is not None:
        payload = json.loads((path or FAMILIES_PATH).read_text())
        sigs = payload.get("oracle_signals") or {}
        if path is None:
            _SIGNALS = sigs
        return sigs
    return _SIGNALS


def clear_cache() -> None:
    """Drop memoized objects/signals. Tests call this after rewriting JSON."""
    global _OBJECTS, _SIGNALS
    _OBJECTS = None
    _SIGNALS = None


def _oracle(card: dict) -> str | None:
    """Oracle text, including both faces. None when we could not look.

    CRITICAL: this app's deck cards carry oracle text as `text`, NOT
    `oracle_text` -- see the shape returned by /api/build. Reading only
    `oracle_text` silently yields an empty string for every card in a real
    deck, so every profile comes back with no objects and the orphan gate
    either blocks everything or nothing. Measured: a probe reading the wrong
    key reported "0 of 99" for all nine probes including card draw. Accept
    both keys.

    Present empty string (Scryfall's shape for vanilla creatures — Isamaru,
    Barktooth Warbeard, …) is readable emptiness: we looked, the card has no
    rules text. That is a real zero, not UNKNOWN. None / missing field means
    we could not look. conflating the two left 21 legal commanders
    without a mechanics profile.
    """
    parts: list[str] = []
    # True when a string field was present (including ""). Explicit null is
    # unreadable — same as a missing field.
    saw_string = False
    for key in ("text", "oracle_text"):
        if key not in card:
            continue
        text = card.get(key)
        if text is None:
            continue
        if not isinstance(text, str):
            continue
        saw_string = True
        if text.strip():
            parts.append(text)
            break
    for face in card.get("card_faces") or []:
        if not isinstance(face, dict):
            continue
        for key in ("oracle_text", "text"):
            if key not in face:
                continue
            ft = face.get(key)
            if not isinstance(ft, str):
                continue
            saw_string = True
            if ft.strip():
                parts.append(ft)
                break
    if parts:
        return "\n".join(parts)
    if saw_string:
        return ""
    return None


def catalog_keywords(card: dict) -> list[str]:
    """Scryfall keyword catalog entries on the card — not oracle_signals.

    flying/trample/… are already indexed by Scryfall. Surfacing them
    here lets coverage and callers know we can *read* the card without inventing
    signal regexes that fake produce/consume edges.
    """
    raw = card.get("keywords")
    if not isinstance(raw, list):
        return []
    out = []
    for k in raw:
        if isinstance(k, str) and k.strip():
            out.append(k.strip())
    return out


def profile(card: dict) -> dict[str, Any]:
    """Card -> {produces, consumes, signals, keywords, status}.

    status is "ok" when the oracle text was readable, UNKNOWN when it was not.
    An unknown carries EMPTY sets, and callers must branch on status rather
    than on emptiness -- a readable card with no synergy objects (Sol Ring)
    and an unreadable card are different facts.

    `keywords` are Scryfall catalog values. They are never copied into
    `signals` and do not create produce/consume objects by themselves.
    """
    text = _oracle(card)
    if text is None:
        return {"produces": set(), "consumes": set(),
                "signals": [], "keywords": [], "status": UNKNOWN}

    low = text.lower()
    objects = load_objects()
    produces: set[str] = set()
    consumes: set[str] = set()
    hits: list[str] = []

    for name, sig in load_signals().items():
        for pattern in sig.get("patterns") or []:
            # IGNORECASE: mechanic_families patterns mix case; text is lowered.
            # Same flag mechanics.py uses when compiling oracle_signals.
            if re.search(pattern, low, re.IGNORECASE):
                hits.append(name)
                # The closed set is enforced here: an object a signal names but
                # the catalog does not know is dropped, not trusted.
                produces |= {o for o in sig.get("produces") or [] if o in objects}
                consumes |= {o for o in sig.get("consumes") or [] if o in objects}
                break

    # A permanent on the battlefield IS its types. Without this, every creature
    # that does not also name "creature" in its rules text is invisible to a
    # sacrifice outlet — and an expert Hei Bai 99 reads as mostly orphans.
    # Only permanent_type objects from the closed set; never invent a type.
    type_line = (card.get("type_line") or card.get("type") or "").lower()
    if type_line:
        for obj, meta in objects.items():
            if meta.get("kind") == "permanent_type" and obj in type_line:
                produces.add(obj)

    return {"produces": produces, "consumes": consumes,
            "signals": sorted(set(hits)),
            "keywords": catalog_keywords(card),
            "status": "ok"}

def edges(a: dict, b: dict) -> list[str]:
    """Objects flowing a -> b. The objects ARE the explanation.

    Returns objects rather than a score on purpose: why.py can read an edge
    aloud ("makes treasures -> your commander eats artifacts") without a model
    inventing a reason.

    An UNKNOWN profile forms no edge in either direction. That is not the same
    as "no synergy" -- callers that need the distinction should check
    profile(...)["status"] themselves.
    """
    pa, pb = profile(a), profile(b)
    if pa["status"] == UNKNOWN or pb["status"] == UNKNOWN:
        return []
    return sorted(pa["produces"] & pb["consumes"])


def demand_profile(commander: dict) -> dict[str, Any]:
    """What the commander needs from the 99, and what it offers back.

    Same shape as profile(). Named separately because it is the thing
    candidate cards are matched against, and because the tutorial's step 2 is
    exactly this: break the commander down, then find cards that serve it.
    """
    return profile(commander)


def card_read_status(card: dict) -> str:
    """ok | unread | unknown — Know Magic honesty for synergy copy.

    unknown: no oracle text (could not look).
    unread: oracle present but no signal ∧ no keyword (could not read).
    ok: at least one oracle_signal or Scryfall catalog keyword — may claim
    real none when edges are empty.
    """
    p = profile(card)
    if p.get("status") == UNKNOWN:
        return UNKNOWN
    if p.get("signals") or p.get("keywords"):
        return "ok"
    return UNREAD


def synergy_read_note(card: dict, commander: dict | None = None) -> str:
    """Copy for unknown/unread with no named edges. Empty when real none/connected.

    UI/API must say could-not-read, not score unread/unknown as zero
    synergy. When edges exist (type-line glue), return "" so callers keep the
    edge clause.
    """
    cmdr = commander or {}
    statuses = {card_read_status(card)}
    if cmdr:
        statuses.add(card_read_status(cmdr))
    if UNKNOWN in statuses or UNREAD in statuses:
        if cmdr and (edges(card, cmdr) or edges(cmdr, card)):
            return ""
        return COULD_NOT_READ
    return ""


def cohesion(deck: list[dict], commander: dict) -> dict[str, Any]:
    """Deck-level shape of the graph.

    hub_dependence is the fraction of all edges that touch the commander --
    the measurable form of the tutorial's "a hallmark of a really good deck is
    to be able to never play your commander and still win the game". A deck
    whose every edge runs through its hub shatters when the hub is answered.

    Cards we could not look at are `unknown`. Cards with oracle but no
    signal∧keyword and no edges are `unread`. Neither is an orphan — orphan
    means readable with none we can name.
    """
    graded = []
    unknown = 0
    for card in deck:
        if profile(card)["status"] == UNKNOWN:
            unknown += 1
        else:
            graded.append(card)

    total = 0
    to_commander = 0
    connected: set[int] = set()

    for i, card in enumerate(graded):
        n = len(edges(card, commander)) + len(edges(commander, card))
        if n:
            total += n
            to_commander += n
            connected.add(i)

    for i, a in enumerate(graded):
        for j, b in enumerate(graded):
            if i >= j:
                continue
            n = len(edges(a, b)) + len(edges(b, a))
            if n:
                total += n
                connected.add(i)
                connected.add(j)

    orphans = 0
    unread = 0
    for i, card in enumerate(graded):
        if i in connected:
            continue
        if card_read_status(card) == UNREAD:
            unread += 1
        else:
            orphans += 1

    return {
        "edges": total,
        "orphans": orphans,
        "unknown": unknown,
        "unread": unread,
        "hub_dependence": (to_commander / total) if total else 0.0,
    }


# Roles the graph governs. Everything else -- lands, ramp, draw, spot, wipe --
# is a playability question, not a synergy one. Sol Ring is not a weak synergy
# card; it is not a synergy card. See the sibling curve spec.
GATED_ROLES = frozenset({"theme", "plan"})


def edge_count(card: dict, commander: dict, scaffold: list[dict]) -> int:
    """How many objects connect this card to the commander and the scaffold.

    A COUNT, for tiebreaking within sim-score bands. Never multiplied by a
    coefficient and added to a sim score: showed a threshold's value
    silently decides which KIND of card wins, and an invented weight here
    would silently choose a deck style.
    """
    if profile(card)["status"] == UNKNOWN:
        return 0
    n = len(edges(card, commander)) + len(edges(commander, card))
    for other in scaffold:
        n += len(edges(card, other)) + len(edges(other, card))
    return n


# Timing multipliers change how often abilities fire. They produce no material
# object, so the graph correctly scores them 0 — and that 0 is "cannot see,"
# not "no synergy." STEER must not treat that unrepresentable zero
# as an orphan vote.
_TIMING_MULTIPLIER_PATTERNS = tuple(
    re.compile(p, re.IGNORECASE) for p in (
        r"additional combat phases?",
        r"extra combat phases?",
        r"additional combat(?! damage)",
        r"take an extra turn after this one",
        r"extra turn after this one",
        r"untap all (?:nonland )?permanents",
        r"untap all (?:nonland )?lands",
        r"untap all creatures",
    )
)


def timing_multiplier(card: dict) -> bool:
    """True when oracle multiplies activations via combat / turns / untap-all.

    Extra combats, extra turns, and untap-all are structurally invisible to
    the produce→consume graph. Detected here so STEER can withhold an edge
    vote rather than inventing combat/turn objects.
    """
    text = _oracle(card)
    if text is None:
        return False
    return any(p.search(text) for p in _TIMING_MULTIPLIER_PATTERNS)


def edge_steer_vote(
    card: dict, commander: dict, scaffold: list[dict],
) -> int | None:
    """Edge count for STEER sorting, or None when the card casts no vote.

    Three zeros STEER must not collapse:
      * unknown — could not read (returns 0; fail-open on the gate)
      * orphan — readable, no shared material object (returns 0)
      * unrepresentable timing — readable, but timing_multiplier with 0
        material edges (returns None = omit the edge key)

    None is not a high score. Callers must skip the edge dimension, not
    treat None as zero and sort last.
    """
    n = edge_count(card, commander, scaffold)
    if n == 0 and timing_multiplier(card):
        return None
    return n


# soft prefer glued cards when scores (or fill order) otherwise tie.
# A flag — not a weight. Off = orphans and edged cards stay equal (tests).
STEER = True


# Roles that are never thesis payoffs — mana base, not the plan.
_GLUED_PAYOFF_SKIP_ROLES = frozenset({"basic", "lands"})


def glued_payoff_candidates(
    deck: list[dict],
    commander: dict | None,
    *,
    cap: int = 30,
) -> dict[str, Any]:
    """Allowlist of deck cards glued to the commander.

    Seed: ≥1 directed edge to/from the commander. Grow: edges to any card
    already on the list. Cap is display-only; never pads with ungated names.
    Exact names from the deck only. Unknown commander → status unknown (not
    empty). Lands/basics are skipped — they are not the plan.

    Returns:
      {
        "status": "ok" | "unknown" | "empty",
        "candidates": [{"name", "edge_count"}, …],
        "names": [str, …],
      }
    """
    cmdr = commander or {}
    if profile(cmdr)["status"] == UNKNOWN:
        return {"status": "unknown", "candidates": [], "names": []}

    pool: list[dict] = []
    for c in deck or []:
        if not isinstance(c, dict) or not c.get("name"):
            continue
        role = (c.get("role") or "").lower()
        if role in _GLUED_PAYOFF_SKIP_ROLES:
            continue
        if "land" in (c.get("type") or c.get("type_line") or "").lower() and (
                role in ("", "lands", "basic") or "basic" in role):
            continue
        if profile(c)["status"] == UNKNOWN:
            continue
        pool.append(c)

    if not pool:
        return {"status": "empty", "candidates": [], "names": []}

    by_name = {c["name"]: c for c in pool}
    seed: list[str] = []
    for c in pool:
        if edge_count(c, cmdr, []):
            seed.append(c["name"])

    glued: set[str] = set(seed)
    # Grow via edges to already-glued cards (one hop of scaffold expansion).
    changed = True
    while changed:
        changed = False
        scaffold = [by_name[n] for n in glued if n in by_name]
        for c in pool:
            if c["name"] in glued:
                continue
            if edge_count(c, cmdr, scaffold):
                glued.add(c["name"])
                changed = True

    if not glued:
        return {"status": "empty", "candidates": [], "names": []}

    scaffold_all = [by_name[n] for n in glued if n in by_name]
    ranked = sorted(
        glued,
        key=lambda n: (-edge_count(by_name[n], cmdr, scaffold_all), n),
    )[: max(1, int(cap))]
    candidates = [
        {"name": n, "edge_count": edge_count(by_name[n], cmdr, scaffold_all)}
        for n in ranked
    ]
    return {
        "status": "ok",
        "candidates": candidates,
        "names": [c["name"] for c in candidates],
    }


def payoff_edge_coverage(
    payoff_names: list[str],
    deck: list[dict],
    commander: dict | None,
) -> float:
    """Fraction of named payoffs with ≥1 edge to commander. Unknown ≠ edged."""
    if not payoff_names:
        return 0.0
    by_name = {c["name"]: c for c in (deck or []) if isinstance(c, dict) and c.get("name")}
    cmdr = commander or {}
    edged = 0
    counted = 0
    for n in payoff_names:
        card = by_name.get(n)
        if not card:
            continue
        counted += 1
        if profile(card)["status"] == UNKNOWN or profile(cmdr)["status"] == UNKNOWN:
            continue
        if edge_count(card, cmdr, []):
            edged += 1
    if counted == 0:
        return 0.0
    return edged / counted


def prefer_glued(
    cards: list[dict],
    commander: dict | None,
    scaffold: list[dict] | None = None,
) -> list[dict]:
    """Reorder so higher edge_count comes first. Stable for ties. Never drops.

    Three meanings of a 0-edge reading — do not collapse them:
      * unknown profile — could not look; scores 0 (eligible elsewhere)
      * orphan — readable, no shared produce/consume object; sorts last
      * unrepresentable timing — timing_multiplier with 0 material edges;
        casts no edge vote. Sorted in a neutral band above true
        orphans so STEER does not punish Full Throttle-class cards as if
        they were Shock. Does not invent combat/turn objects or weights.

    Orphans stay in the list — thin pools still complete.
    """
    if not STEER or not cards:
        return list(cards)
    cmdr = commander or {}
    scaf = scaffold or []

    def price_tertiary(c: dict) -> float:
        raw = c.get("usd")
        if raw in (None, ""):
            return -1e9
        try:
            return -float(raw)
        except (TypeError, ValueError):
            return -1e9

    def sort_key(ic: tuple[int, dict]) -> tuple:
        i, c = ic
        vote = edge_steer_vote(c, cmdr, scaf)
        if vote is None:
            # Neutral band: above orphan zeros, no invented positive count.
            return (1, 0, price_tertiary(c), -i)
        if vote > 0:
            return (2, vote, price_tertiary(c), -i)
        return (0, 0, price_tertiary(c), -i)

    ranked = sorted(enumerate(cards), key=sort_key, reverse=True)
    return [c for _, c in ranked]


def eligible(card: dict, commander: dict, scaffold: list[dict]) -> bool:
    """May this card fill a gated slot?

    An UNKNOWN profile is eligible. We could not read the card, so we have no
    evidence against it, and refusing it would quietly shrink the pool -- a
    fallback dressed as a match.
    """
    if profile(card)["status"] == UNKNOWN:
        return True
    return edge_count(card, commander, scaffold) > 0


def leave_enabler_queries(commander: dict) -> list[str]:
    """Scryfall queries for cards that cause the commander to leave.

    When the commander triggers on leaving the battlefield, sac outlets and
    blink both pay it off. Sac arrives via dies_triggers / sacrifice theme
    search; blink does not. The leave-causation probe measured zero blink in a Hei Bai 99 while
    otag:blink returns 102 cards in WB — recall, not ranking (same shape as
    The archetype payoff floors). An unknown commander asks for nothing; we could not look.

    also reachable through synergy_recall_queries(); keep this entry
    point so the Hei Bai blink floor does not regress.
    """
    demand = demand_profile(commander)
    if demand["status"] == UNKNOWN:
        return []
    if "leaves_battlefield" not in demand["signals"]:
        return []
    return ["otag:blink"]


# oracle_signals family names that are not mechanic_families keys.
_FAMILY_ALIASES = {
    "counters": "counters_plus",
    "combat_triggers": "attacking_triggers",
    "recursion": "return_from_graveyard",
    "spellslinger": "when_you_cast",
    "landfall": "etb_triggers",
}


def _normalize_family(fam: str) -> str:
    return _FAMILY_ALIASES.get(fam, fam)


def _demand_families(commander: dict) -> list[str] | None:
    """Seed families from demand signals. None = unknown (could not look)."""
    demand = demand_profile(commander)
    if demand["status"] == UNKNOWN:
        return None
    signals_meta = load_signals()
    out: set[str] = set()
    for sig in demand["signals"]:
        meta = signals_meta.get(sig) or {}
        fam = meta.get("family")
        if fam:
            out.add(_normalize_family(fam))
    return sorted(out)


def _family_payoff_query(family: str) -> str | None:
    """Payoff Scryfall pattern for a family, when plan_graph knows one.

    Lazy import: plan_graph imports synergy at module level. Called only after
    both modules are loaded (build / tests), never during synergy import.
    """
    from deckwright import plan_graph  # noqa: PLC0415 — break the cycle; see docstring
    return (plan_graph._PAYOFF_QUERIES or {}).get(family)


def _taxonomy_queries_for_family(family: str) -> list[str]:
    """Verified taxonomy supports.queries for mechanics in `family`."""
    from deckwright import mechanics  # noqa: PLC0415 — optional heavy load; keep synergy light

    families = mechanics.load_families()
    body = (families.get("families") or {}).get(family) or {}
    out: list[str] = []
    seen: set[str] = set()
    for mech in body.get("mechanics") or []:
        if not isinstance(mech, str):
            continue
        meta = mechanics.mechanic_meta(mech, families)
        for q in (meta.get("supports") or {}).get("queries") or []:
            if not isinstance(q, str):
                continue
            q = q.strip()
            if not q or q in seen:
                continue
            seen.add(q)
            out.append(q)
    return out


def _queries_for_family(family: str) -> list[str]:
    """Taxonomy supports.queries plus family payoff query when present."""
    out: list[str] = []
    seen: set[str] = set()
    for q in _taxonomy_queries_for_family(family):
        if q not in seen:
            seen.add(q)
            out.append(q)
    pq = _family_payoff_query(family)
    if pq and pq not in seen:
        out.append(pq)
    return out


def _family_plan_role(family: str) -> str | None:
    from deckwright import mechanics  # noqa: PLC0415

    body = ((mechanics.load_families().get("families") or {}).get(family)
            or {})
    role = body.get("plan_role")
    return str(role) if role else None


def _is_enabler_floor(seed: str, neighbor: str, relation: str,
                      direction: str) -> bool:
    """True when `neighbor` is an enabler the seed family needs on the 99.

    tokens feeds dies_triggers → floor (sac fodder). dies_triggers feeds
    life_math → not a floor (payoff expansion; the commitment derivation must not force
    lifegain into the 99). Blink leave-enablers are handled separately.
    """
    if direction != "from":
        # Neighbor is downstream of the seed (seed → neighbor). That is a
        # payoff/compose expansion, not fuel the commander lacks.
        return False
    if relation not in ("feeds", "needs", "pairs", "multiplies"):
        return False
    role = _family_plan_role(neighbor)
    # Enabler families supplying the seed. "engine" token doublers etc. still
    # produce the bodies aristocrats spend — treat enabler-shaped roles only.
    return role == "enabler"


def synergy_neighbors(commander: dict) -> list[dict]:
    """One-hop relation neighbors for candidate recall.

    Path: demand signals → families → one-hop `relations` → taxonomy
    `supports.queries` and family payoff queries where present.

    Returns a list of
      {family, via, queries, plan_role, enabler_floor}
    sorted by family name. Unknown commander → [] (not a fake zero).

    Relations expand ONLY for candidate recall. plan_graph stays demand-only
    — expanding dies_triggers→life_math into commitments invented lifegain
    for Hei Bai.
    """
    from deckwright import mechanics  # noqa: PLC0415

    seeds = _demand_families(commander)
    if seeds is None:
        return []
    seed_set = set(seeds)
    # family → list of via edges that discovered it
    found: dict[str, list[dict]] = {}
    floor_families: set[str] = set()

    for seed in seeds:
        for edge in mechanics.family_relations(seed):
            other = edge.get("family")
            if not other or other in seed_set:
                continue
            other = _normalize_family(str(other))
            if other in seed_set:
                continue
            rel = str(edge.get("relation") or "related")
            direction = str(edge.get("direction") or "")
            found.setdefault(other, []).append({
                "from": seed,
                "relation": rel,
                "direction": direction,
            })
            if _is_enabler_floor(seed, other, rel, direction):
                floor_families.add(other)

    out: list[dict] = []
    for fam in sorted(found):
        queries = _queries_for_family(fam)
        if not queries:
            # A hop with nothing to search is not a neighbor we can recall.
            # Skip rather than emit an empty pool entry that looks like a zero.
            continue
        out.append({
            "family": fam,
            "via": found[fam],
            "queries": queries,
            "plan_role": _family_plan_role(fam),
            "enabler_floor": fam in floor_families,
        })
    return out


def recall_queries_for_neighbor(neighbor: dict) -> list[str]:
    """Queries the build should actually search for one neighbor.

    Prefer the family payoff pattern (one Scryfall round-trip). Taxonomy
    supports.queries fill in when there is no payoff pattern, and always
    accompany enabler floors — tokens' payoff query finds ETB payoffs, not
    the token makers aristocrats need as sac fodder.
    """
    fam = neighbor.get("family") or ""
    all_qs = [q for q in (neighbor.get("queries") or [])
              if isinstance(q, str) and q.strip()]
    pq = _family_payoff_query(fam)
    out: list[str] = []
    if pq:
        out.append(pq)
    tax = [q for q in all_qs if q != pq]
    if neighbor.get("enabler_floor") or not pq:
        # Cap: a family can carry dozens of keyword: leaves; the build cannot
        # afford one search each. Eight arms still cover the common makers.
        out.extend(tax[:8])
    return out


def synergy_recall_queries(commander: dict) -> list[str]:
    """Flatten/dedupe neighbor + leave-enabler queries for the build pool.

    Unknown commander → []. leave_enabler_queries is called through here so
    the Hei Bai blink recall cannot drift off the generalized path.
    """
    out: list[str] = []
    seen: set[str] = set()
    for n in synergy_neighbors(commander):
        for q in recall_queries_for_neighbor(n):
            if q not in seen:
                seen.add(q)
                out.append(q)
    for q in leave_enabler_queries(commander):
        if q not in seen:
            seen.add(q)
            out.append(q)
    return out
